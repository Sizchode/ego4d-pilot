"""Extract protocol-defined compact/distributed features on HPC."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from .adapters import build_adapter
from .feature_store import save_feature_file
from .manifest import read_jsonl
from .protocol import load_protocol_config


def _prompts(records, model_name: str, prompts_file: str | None) -> list[str]:
    if model_name == "vjepa2_vitl":
        return [""] * len(records)
    if not prompts_file:
        raise ValueError("provide prompts generated by the relevant official model implementation")
    with Path(prompts_file).expanduser().resolve().open("r", encoding="utf-8") as handle:
        prompts_by_id = json.load(handle)
    if not isinstance(prompts_by_id, dict):
        raise ValueError("prompts file must map manifest example_id to the exact official prompt string")
    prompts = [prompts_by_id.get(record.example_id) for record in records]
    if any(not isinstance(prompt, str) or not prompt for prompt in prompts):
        raise ValueError("prompts file is missing an exact prompt for at least one manifest example")
    return prompts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=str(Path(__file__).with_name("config.yaml")))
    parser.add_argument("--model", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--prompts-file")
    parser.add_argument("--readouts", nargs="+", choices=("compact", "distributed"), default=("compact", "distributed"))
    parser.add_argument("--device", default="cuda")
    args = parser.parse_args()

    _, config = load_protocol_config(args.config)
    if args.model not in config["models"]:
        raise ValueError(f"unknown model: {args.model}")
    records = read_jsonl(args.manifest)
    prompts = _prompts(records, args.model, args.prompts_file)
    adapter = build_adapter(config["models"][args.model], args.device)
    compact = adapter.extract_compact_state([record.video_path for record in records], prompts) if "compact" in args.readouts else {}
    distributed = adapter.extract_distributed_state([record.video_path for record in records], prompts) if "distributed" in args.readouts else {}
    if any(record.label_id is None and record.dataset == "ssv2" for record in records):
        raise ValueError("SSv2 probe features require label_id from the official label map")
    labels = [record.label_id if record.dataset == "ssv2" else record.answer_index for record in records]
    if any(label is None for label in labels):
        raise ValueError("feature labels are incomplete")
    categories = [record.category for record in records] if records[0].dataset == "nextqa" else None
    save_feature_file(
        args.output,
        dataset=records[0].dataset,
        model=args.model,
        split=records[0].split,
        total_layers=adapter.total_layers,
        example_ids=[record.example_id for record in records],
        labels=[int(label) for label in labels],
        categories=categories,
        compact=compact,
        distributed=distributed,
    )


if __name__ == "__main__":
    main()
